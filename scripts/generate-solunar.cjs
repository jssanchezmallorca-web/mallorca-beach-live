#!/usr/bin/env node
'use strict';

// Pinned, locally vendored engines; generation does not need an API or npm install.
const {calculateSolunarPeriods} = require('./vendor/bite-times.cjs');
const {writeFileSync} = require('node:fs');
const {resolve} = require('node:path');

const TIME_ZONE = 'Europe/Madrid';
const LATITUDE = 39.65;
const LONGITUDE = 3.0;
const DAY_MS = 86400000;

function mallorcaDate(date) {
  const parts = new Intl.DateTimeFormat('en-CA', {
    timeZone: TIME_ZONE, year: 'numeric', month: '2-digit', day: '2-digit'
  }).formatToParts(date);
  const get = name => parts.find(part => part.type === name).value;
  return `${get('year')}-${get('month')}-${get('day')}`;
}

function generate(today = mallorcaDate(new Date())) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(today) ||
      new Date(`${today}T00:00:00Z`).toISOString().slice(0, 10) !== today) {
    throw new Error('Expected a valid YYYY-MM-DD date');
  }
  const start = Date.parse(`${today}T00:00:00Z`) - 2 * DAY_MS;
  const days = Array.from({length: 402}, (_, index) => {
    const date = new Date(start + index * DAY_MS);
    const value = calculateSolunarPeriods(LATITUDE, LONGITUDE, date, TIME_ZONE);
    if (!Number.isFinite(value.dayRating) || value.dayRating < 0 || value.dayRating > 5) {
      throw new Error(`Invalid solunar value for ${date.toISOString()}`);
    }
    return [date.toISOString().slice(0, 10), value.dayRating];
  });
  return {
    generatedFor: today,
    timeZone: TIME_ZONE,
    location: {name: 'Mallorca', latitude: LATITUDE, longitude: LONGITUDE},
    engine: {name: 'bite-times', version: '1.1.1', source: 'https://github.com/benpaternostro/bite-times'},
    days
  };
}

if (require.main === module) {
  const data = generate(process.argv[2]);
  writeFileSync(resolve(__dirname, '../solunar-data.js'),
    '// Solunar guidance for Mallorca. Generated by scripts/generate-solunar.cjs.\n' +
    'window.BC_SOLUNAR_DATA=' + JSON.stringify(data) + ';\n');
  console.log(`Mallorca solunar: ${data.days.length} days from ${data.days[0][0]} (${TIME_ZONE})`);
}

module.exports = {generate, mallorcaDate};
